    !---------------------------------------------------------------------
    ! Region 3 密度計算メイン関数
    ! Input: T [K], P [Pa], region_id (詳細ID)
    ! Output: rho [kg/m^3]
    !---------------------------------------------------------------------
    module pure elemental function calc_rho_iapws97_region3(T_in, P_in, id) result(rho)
        real(real64), intent(in) :: T_in, P_in
        integer(int32), intent(in) :: id
        real(real64) :: rho
        real(real64) :: v

