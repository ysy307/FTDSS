        end if
    end function calc_rho_iapws97_region3

    !---------------------------------------------------------------------
    ! 比体積計算 v(p,T) - SR5-05 Eq(4) & Eq(5)
    !---------------------------------------------------------------------
    module pure elemental function calc_nu_iapws97_region3(T_in, P_in, id) result(v)
        implicit none
        real(real64), intent(in) :: T_in, P_in
        integer(int32), intent(in) :: id
        real(real64) :: v

        real(real64) :: v_star, p_star, T_star
        real(real64) :: a, b, c, d, e
        type(r3_coeff_type) :: coeffs

        real(real64) :: pi, theta, term_p, term_t, summation
        integer :: k

        ! 1. パラメータの取得
        call get_r3_params(id, v_star, p_star, T_star, a, b, c, d, e)

        ! 2. 係数の取得
        coeffs = get_r3_coeffs_data(id)

        ! 3. 無次元変数の計算
        pi = P_in / (p_star * 1.0d6) ! Pa -> MPa変換して正規化
        theta = T_in / T_star

        ! 4. 式の適用
        if (id == IAPWS97_R3_N) then
            ! --- Eq (5): Exponential Form (Subregion 3n only) ---
            summation = 0.0d0
            if (allocated(coeffs%n)) then
                do k = 1, size(coeffs%n)
                    summation = summation + coeffs%n(k) * &
                                ((pi - a)**coeffs%I(k)) * &
                                ((theta - b)**coeffs%J(k))
                end do
            end if
            v = v_star * exp(summation)
        else
            ! --- Eq (4): Standard Form ---
            ! omega = [ sum n_i * {(pi-a)^c}^Ii * {(theta-b)^d}^Ji ]^e

            ! 基底項の計算 (負の底に対する実数乗算エラーを防ぐため複素数化はせず、定義域内前提)
            term_p = (pi - a)**c
            term_t = (theta - b)**d

            summation = 0.0d0
            if (allocated(coeffs%n)) then
                do k = 1, size(coeffs%n)
                    summation = summation + coeffs%n(k) * &
                                (term_p**coeffs%I(k)) * &
                                (term_t**coeffs%J(k))
                end do
            end if
            v = v_star * (summation**e)
        end if

    end function calc_nu_iapws97_region3

